import Foundation

// A profile file J700.swift defines J700.profile. The compiler verifies the
// definition and type; this tool only discovers product-number filenames.
do {
    let arguments = Array(CommandLine.arguments.dropFirst())
    guard let output = arguments.first, arguments.count > 1 else {
        throw NSError(domain: "BoardDiscovery", code: 1, userInfo: [NSLocalizedDescriptionKey: "No board profiles found"])
    }
    let names = try arguments.dropFirst().map { path -> String in
        let name = URL(fileURLWithPath: path).deletingPathExtension().lastPathComponent
        guard name.range(of: #"^J[0-9]+[a-z]?$"#, options: .regularExpression) != nil else {
            throw NSError(domain: "BoardDiscovery", code: 2, userInfo: [NSLocalizedDescriptionKey: "Board profile filenames must use a product number, such as J700.swift: \(path)"])
        }
        return name
    }.sorted()
    let entries = names.map { "        \($0).profile" }.joined(separator: ",\n")
    let source = """
    // Generated by BoardDiscovery. Do not edit.
    enum DiscoveredBoards {
        static let profiles: [BoardProfile] = [
    \(entries)
        ]
    }

    """
    try source.write(toFile: output, atomically: true, encoding: .utf8)
} catch {
    FileHandle.standardError.write(Data((error.localizedDescription + "\n").utf8))
    exit(1)
}
